export type EventRecurrenceRule = 'daily' | 'weekly' | 'biweekly' | 'monthly';

export interface CalendarEvent {
  id: string;
  title: string;
  description: string;
  location: string;
  startIso: string;
  endIso: string;
  allDay: boolean;
  /** One or more family member IDs associated with this event */
  memberIds: string[];
  calendarSourceId: string | null;
  externalEventId: string | null;
  updatedAt: string;
  /** Birthday / holiday events get their own color and can be hidden as a group */
  category?: import('./eventCategories.js').EventCategory | null;
  /** Recurrence cadence for repeating series */
  recurrenceRule?: EventRecurrenceRule | null;
  /** True if this instance is dynamically generated by recurrence expansion */
  isRecurringInstance?: boolean;
  /** ID of the parent recurring event for virtual instances */
  originalEventId?: string;
  /** Dates (YYYY-MM-DD) excluded from recurrence projection */
  exceptionDates?: string[];
  /** Minutes needed to get there; drives the "leave in 15 min" banner (Lucarne-only, not sent to Google) */
  travelMinutes?: number | null;
  /** Who is driving / taking them (Lucarne-only) */
  driverMemberId?: string | null;
  /** Set for read-only events from a subscribed calendar feed (ICS) */
  icsFeedId?: string | null;
}

