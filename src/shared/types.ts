export interface Chore {
  id: string;
  title: string;
  emoji: string;
  /** null means shared / "Up for grabs" (anyone can complete & claim stars) */
  assignedMemberId: string | null;
  timeOfDay: ChoreTimeOfDay;
  frequency: ChoreFrequency;
  /** 0 (Sun) - 6 (Sat) when frequency === 'weekly' */
  daysOfWeek: number[];
  /** Specific YYYY-MM-DD when frequency === 'once' */
  specificDate: string | null;
  stars: number;
  active: boolean;
  sortOrder: number;
}

